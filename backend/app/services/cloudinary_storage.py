import hashlib
import uuid
from time import time
from urllib.request import urlopen

import cloudinary
import cloudinary.uploader
import cloudinary.utils

from app.core.config import get_settings
from app.core.errors import AppError

ALLOWED_TYPES = {"image/jpeg", "image/png", "image/webp", "application/pdf"}


def configure_cloudinary() -> None:
    settings = get_settings()
    if not all(
        (
            settings.cloudinary_cloud_name,
            settings.cloudinary_api_key,
            settings.cloudinary_api_secret,
        )
    ):
        raise AppError("storage_not_configured", "Cloudinary storage is not configured", 503)
    cloudinary.config(
        cloud_name=settings.cloudinary_cloud_name,
        api_key=settings.cloudinary_api_key,
        api_secret=settings.cloudinary_api_secret,
        secure=True,
    )


def upload_evidence(
    content: bytes, filename: str, media_type: str, workspace_id: uuid.UUID
) -> dict:
    settings = get_settings()
    configure_cloudinary()
    if media_type not in ALLOWED_TYPES:
        raise AppError(
            "unsupported_media_type", "Only PDF, JPEG, PNG, and WebP evidence is accepted", 415
        )
    if len(content) > settings.max_document_bytes:
        raise AppError("file_too_large", "Evidence file exceeds the configured limit", 413)
    digest = hashlib.sha256(content).hexdigest()
    public_id = f"tallytrail/{workspace_id}/{uuid.uuid4()}"
    try:
        uploaded = cloudinary.uploader.upload(
            content,
            public_id=public_id,
            resource_type="auto",
            type="authenticated",
            overwrite=False,
            unique_filename=False,
            filename_override=filename,
            context={"sha256": digest, "workspace_id": str(workspace_id)},
        )
    except Exception as exc:
        raise AppError("storage_upload_failed", "Evidence upload failed", 502) from exc
    return {"sha256": digest, "public_id": public_id, **uploaded}


def signed_download_url(public_id: str, resource_type: str, file_format: str) -> str:
    configure_cloudinary()
    return cloudinary.utils.private_download_url(
        public_id,
        file_format,
        resource_type=resource_type,
        type="authenticated",
        expires_at=int(time()) + 3600,
    )


def remote_sha256(public_id: str, resource_type: str, file_format: str, max_bytes: int) -> str:
    url = signed_download_url(public_id, resource_type, file_format)
    digest = hashlib.sha256()
    total = 0
    with urlopen(url, timeout=20) as response:  # noqa: S310 - URL is generated by Cloudinary
        while chunk := response.read(64 * 1024):
            total += len(chunk)
            if total > max_bytes:
                raise AppError(
                    "integrity_check_too_large", "Stored file exceeds the configured limit", 409
                )
            digest.update(chunk)
    return digest.hexdigest()
